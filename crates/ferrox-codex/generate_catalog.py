import os
import glob
import re

BASE_DIR = r"C:\Users\nn\Desktop\code\ferrox-docs\docs"
OUT_FILE = r"C:\Users\nn\Desktop\code\ferrox-front\crates\ferrox-codex\src\generated_ecosystem_docs.rs"

files = glob.glob(os.path.join(BASE_DIR, "**", "*.md"), recursive=True)
files = sorted(files)

print(f"Discovered {len(files)} markdown files in {BASE_DIR}")

entries = []

for filepath in files:
    rel = os.path.relpath(filepath, BASE_DIR).replace("\\", "/")
    route = rel
    if route.endswith(".md"):
        route = route[:-3]
    
    # Read file
    with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()

    # Extract title
    title = None
    sidebar_pos = 999
    
    fm_match = re.search(r"^---\s*\n(.*?)\n---", content, re.DOTALL)
    if fm_match:
        fm = fm_match.group(1)
        t_match = re.search(r"title:\s*[\"']?(.*?)[\"']?\s*$", fm, re.MULTILINE)
        if t_match:
            title = t_match.group(1).strip()
        pos_match = re.search(r"sidebar_position:\s*(\d+)", fm)
        if pos_match:
            sidebar_pos = int(pos_match.group(1))

    if not title:
        h1_match = re.search(r"^#\s+(.+)$", content, re.MULTILINE)
        if h1_match:
            title = h1_match.group(1).strip()
            # Clean markdown links or formatting from title
            title = re.sub(r"\[(.*?)\]\(.*?\)", r"\1", title)
            title = title.replace("`", "").strip()

    if not title:
        # Basename fallback
        base_name = os.path.splitext(os.path.basename(rel))[0]
        title = base_name.replace("-", " ").replace("_", " ").title()

    # Relative path from crates/ferrox-codex to the markdown file
    # crates/ferrox-codex -> ../../../../ferrox-docs/docs/...
    include_path = f"../../../../ferrox-docs/docs/{rel}"

    entries.append({
        "route": route,
        "title": title,
        "sidebar_pos": sidebar_pos,
        "include_path": include_path,
        "rel": rel
    })

# Group entries by top-level section
sections = {}
for e in entries:
    parts = e["route"].split("/")
    top = parts[0]
    if top not in sections:
        sections[top] = []
    sections[top].append(e)

# Generate Rust code
code_lines = [
    "// AUTO-GENERATED BY generate_catalog.py - DO NOT EDIT MANUALLY",
    "// Ingests all 315 ecosystem documentation files from ferrox-docs/docs",
    "",
    "use crate::registry::DocRegistry;",
    "use ferrox_front_ui::DocNavItem;",
    "",
    "pub fn register_all_ecosystem_docs(registry: &mut DocRegistry) {",
]

for e in entries:
    r = e["route"]
    inc = e["include_path"]
    code_lines.append(f'    registry.register("{r}", include_str!("{inc}"));')

code_lines.append("}")
code_lines.append("")

# Generate comprehensive sidebar builder
code_lines.append("pub fn build_complete_ecosystem_sidebar() -> Vec<DocNavItem> {")
code_lines.append("    vec![")

# Order of top sections
ordered_sections = [
    ("overview", "🚀 Getting Started & Overview", "zap"),
    ("ferrox", "🦀 Ferrox (Core Server Framework)", "cpu"),
    ("ferrox-front", "🎨 Ferrox Front (Wasm UI)", "layout"),
    ("ferrox-node", "🟢 Ferrox Node", "server"),
    ("ferrox-py", "🐍 Ferrox Py", "code"),
    ("ferrox-php", "🐘 Ferrox PHP", "globe"),
    ("nestjs-yalc", "⚡ NestJS YALC", "package"),
    ("node-yalc", "📦 Node YALC", "box"),
    ("enterprise-modules", "🏢 Enterprise Modules", "shield"),
    ("benchmarks", "⚡ Benchmarks (1M RPS)", "activity"),
    ("security", "🛡️ Security & Audits", "lock"),
    ("ecosystem", "🌟 Ecosystem Showcase", "star"),
]

section_icons = {
    "ferrox": "cpu",
    "ferrox-front": "layout",
    "ferrox-node": "server",
    "ferrox-py": "code",
    "ferrox-php": "globe",
    "nestjs-yalc": "package",
    "node-yalc": "box",
    "benchmarks": "activity",
    "security": "lock",
    "ecosystem": "star",
    "enterprise-modules": "shield",
    "overview": "zap",
}

for sec_id, sec_label, sec_icon in ordered_sections:
    # Find matching items
    matching = []
    for r, items in sections.items():
        if r == sec_id or (sec_id == "security" and "SECURITY" in r) or (sec_id == "ecosystem" and "ECOSYSTEM" in r):
            matching.extend(items)

    if not matching:
        continue

    # Group matching into subsections (level 2)
    subgroups = {}
    direct_items = []
    for item in matching:
        parts = item["route"].split("/")
        if len(parts) <= 1:
            direct_items.append(item)
        elif len(parts) == 2 and parts[1] == "overview":
            direct_items.insert(0, item)
        else:
            sub = parts[1] if len(parts) > 1 else "general"
            if sub not in subgroups:
                subgroups[sub] = []
            subgroups[sub].append(item)

    code_lines.append(f'        DocNavItem::new("cat-{sec_id}", "{sec_label}")')
    code_lines.append(f'            .with_icon("{sec_icon}")')
    code_lines.append("            .with_children(vec![")

    # Direct items
    for item in direct_items:
        r = item["route"]
        t = item["title"].replace('"', '\\"')
        r_id = r.replace("/", "-")
        code_lines.append(f'                DocNavItem::new("nav-{r_id}", "{t}")')
        code_lines.append(f'                    .with_href("/{r}")')
        code_lines.append('                    .with_icon("file-text"),')

    # Subgroups
    for sub_name, sub_items in sorted(subgroups.items()):
        sub_title = sub_name.replace("-", " ").replace("_", " ").title()
        code_lines.append(f'                DocNavItem::new("sub-{sec_id}-{sub_name}", "{sub_title}")')
        code_lines.append('                    .with_icon("folder")')
        code_lines.append("                    .with_children(vec![")
        
        # Sort sub_items by sidebar_pos, then route
        sub_items.sort(key=lambda x: (x["sidebar_pos"], x["route"]))
        for item in sub_items:
            r = item["route"]
            t = item["title"].replace('"', '\\"')
            r_id = r.replace("/", "-")
            code_lines.append(f'                        DocNavItem::new("nav-{r_id}", "{t}")')
            code_lines.append(f'                            .with_href("/{r}"),')
        
        code_lines.append("                    ]),")

    code_lines.append("            ]),")

code_lines.append("    ]")
code_lines.append("}")
code_lines.append("")

with open(OUT_FILE, "w", encoding="utf-8") as f:
    f.write("\n".join(code_lines))

print(f"Generated {OUT_FILE} with {len(entries)} documents across {len(sections)} sections!")
